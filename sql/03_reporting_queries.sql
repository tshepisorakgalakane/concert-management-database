/*
  03_reporting_queries.sql
  Run after schema creation and sample-data insertion.
  Execute one query at a time in Oracle SQL Developer.
*/

-- 1. Attendees and their ticket details.
SELECT a.ATTENDEE_ID, a.FIRST_NAME, a.LAST_NAME, a.EMAIL,
       t.TICKET_CODE, t.TICKET_TYPE, t.PRICE
FROM ATTENDEE a
LEFT JOIN TICKET t ON t.ATTENDEE_ID = a.ATTENDEE_ID
ORDER BY a.LAST_NAME, a.FIRST_NAME;

-- 2. Artists, their stage and venue.
SELECT ar.ARTIST_NAME, ar.GENRE, ar.TIMESLOT,
       s.STAGE_NAME, s.STAGE_TYPE, v.VENUE_NAME
FROM ARTIST ar
JOIN STAGE s ON s.STAGE_NO = ar.STAGE_NO
JOIN VENUE v ON v.VENUE_ID = s.VENUE_ID
ORDER BY s.STAGE_NAME, ar.TIMESLOT;

-- 3. Attendee count per venue.
SELECT v.VENUE_NAME, COUNT(a.ATTENDEE_ID) AS ATTENDEE_COUNT
FROM VENUE v
LEFT JOIN ATTENDEE a ON a.VENUE_ID = v.VENUE_ID
GROUP BY v.VENUE_NAME
ORDER BY v.VENUE_NAME;

-- 4. Ticket revenue by ticket type (allocated tickets only).
SELECT TICKET_TYPE, COUNT(*) AS TICKETS_ALLOCATED, SUM(PRICE) AS TOTAL_REVENUE
FROM TICKET
WHERE ATTENDEE_ID IS NOT NULL
GROUP BY TICKET_TYPE
ORDER BY TOTAL_REVENUE DESC;

-- 5. Purchases with attendee and stall information.
SELECT p.PURCHASE_ID,
       a.FIRST_NAME || ' ' || a.LAST_NAME AS ATTENDEE_NAME,
       s.STALL_NAME, p.PURCHASED_ITEM, p.QUANTITY, p.UNIT_PRICE,
       p.QUANTITY * NVL(p.UNIT_PRICE, 0) AS LINE_TOTAL, p.PURCHASED_AT
FROM STALL_PURCHASE p
JOIN ATTENDEE a ON a.ATTENDEE_ID = p.ATTENDEE_ID
JOIN STALL s ON s.STALL_NO = p.STALL_NO
ORDER BY p.PURCHASED_AT DESC;

-- 6. Sales summary by stall.
SELECT s.STALL_NO, s.STALL_NAME,
       SUM(NVL(p.QUANTITY, 0)) AS ITEMS_SOLD,
       SUM(NVL(p.QUANTITY * p.UNIT_PRICE, 0)) AS SALES_TOTAL
FROM STALL s
LEFT JOIN STALL_PURCHASE p ON p.STALL_NO = s.STALL_NO
GROUP BY s.STALL_NO, s.STALL_NAME
ORDER BY SALES_TOTAL DESC;

-- 7. Associated attendee count per paramedic team.
SELECT pt.PARAMEDIC_TEAM_ID, pt.COMPANY, pt.SPECIALIZATION,
       COUNT(a.ATTENDEE_ID) AS ASSOCIATED_ATTENDEES
FROM PARAMEDIC_TEAM pt
LEFT JOIN ATTENDEE a ON a.PARAMEDIC_TEAM_ID = pt.PARAMEDIC_TEAM_ID
GROUP BY pt.PARAMEDIC_TEAM_ID, pt.COMPANY, pt.SPECIALIZATION
ORDER BY pt.PARAMEDIC_TEAM_ID;

-- 8. Security teams and optional stage/artist assignments.
SELECT sec.SECURITY_TEAM_ID, sec.COMPANY, sec.STATION,
       st.STAGE_NAME, ar.ARTIST_NAME, v.VENUE_NAME
FROM SECURITY_TEAM sec
LEFT JOIN STAGE st ON st.STAGE_NO = sec.STAGE_NO
LEFT JOIN ARTIST ar ON ar.ARTIST_ID = sec.ARTIST_ID
LEFT JOIN VENUE v ON v.VENUE_ID = sec.VENUE_ID
ORDER BY sec.SECURITY_TEAM_ID;
