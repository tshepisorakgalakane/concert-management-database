  01_create_tables.sql
  Oracle Database

  Run in a clean schema. This script does not drop existing tables.
*/

CREATE TABLE VENUE (
    VENUE_ID       VARCHAR2(10)   CONSTRAINT PK_VENUE PRIMARY KEY,
    VENUE_NAME     VARCHAR2(150)  NOT NULL,
    VENUE_ADDRESS  VARCHAR2(200)  NOT NULL
);

CREATE TABLE PARAMEDIC_TEAM (
    PARAMEDIC_TEAM_ID  VARCHAR2(20)   CONSTRAINT PK_PARAMEDIC_TEAM PRIMARY KEY,
    COMPANY            VARCHAR2(150)  NOT NULL,
    SPECIALIZATION     VARCHAR2(150),
    CELL_NO            VARCHAR2(25)   NOT NULL,
    VENUE_ID           VARCHAR2(10),
    CONSTRAINT FK_PARAMEDIC_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID)
);

CREATE TABLE STAGE (
    STAGE_NO        VARCHAR2(10)   CONSTRAINT PK_STAGE PRIMARY KEY,
    STAGE_NAME      VARCHAR2(150)  NOT NULL,
    STAGE_LOCATION  VARCHAR2(150),
    STAGE_TYPE      VARCHAR2(30)   NOT NULL,
    VENUE_ID        VARCHAR2(10)   NOT NULL,
    CONSTRAINT CK_STAGE_TYPE
        CHECK (STAGE_TYPE IN ('MAIN_STAGE', 'SIDE_STAGE', 'SECONDARY_STAGE')),
    CONSTRAINT FK_STAGE_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID)
);

CREATE TABLE ARTIST (
    ARTIST_ID    VARCHAR2(13)   CONSTRAINT PK_ARTIST PRIMARY KEY,
    ARTIST_NAME  VARCHAR2(150)  NOT NULL,
    TIMESLOT     VARCHAR2(50),
    GENRE        VARCHAR2(100),
    EMAIL        VARCHAR2(254),
    PHONE_NO     VARCHAR2(25)   NOT NULL,
    STAGE_NO     VARCHAR2(10),
    CONSTRAINT UQ_ARTIST_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_ARTIST_STAGE
        FOREIGN KEY (STAGE_NO) REFERENCES STAGE (STAGE_NO)
);

CREATE TABLE SECURITY_TEAM (
    SECURITY_TEAM_ID  VARCHAR2(10)   CONSTRAINT PK_SECURITY_TEAM PRIMARY KEY,
    STATION           VARCHAR2(150),
    COMPANY           VARCHAR2(150)  NOT NULL,
    EMAIL             VARCHAR2(254)  NOT NULL,
    VENUE_ID          VARCHAR2(10),
    STAGE_NO          VARCHAR2(10),
    ARTIST_ID         VARCHAR2(13),
    CONSTRAINT UQ_SECURITY_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_SECURITY_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID),
    CONSTRAINT FK_SECURITY_STAGE
        FOREIGN KEY (STAGE_NO) REFERENCES STAGE (STAGE_NO),
    CONSTRAINT FK_SECURITY_ARTIST
        FOREIGN KEY (ARTIST_ID) REFERENCES ARTIST (ARTIST_ID)
);

CREATE TABLE STALL (
    STALL_NO        VARCHAR2(50)   CONSTRAINT PK_STALL PRIMARY KEY,
    STALL_NAME      VARCHAR2(150)  NOT NULL,
    STALL_LOCATION  VARCHAR2(150),
    STALL_TYPE      VARCHAR2(50)   NOT NULL,
    VENUE_ID        VARCHAR2(10)   NOT NULL,
    CONSTRAINT CK_STALL_TYPE
        CHECK (STALL_TYPE IN ('FOOD', 'DRINKS', 'MERCHANDISE', 'OTHER')),
    CONSTRAINT FK_STALL_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID)
);

CREATE TABLE ATTENDEE (
    ATTENDEE_ID        VARCHAR2(13)   CONSTRAINT PK_ATTENDEE PRIMARY KEY,
    FIRST_NAME         VARCHAR2(100)  NOT NULL,
    LAST_NAME          VARCHAR2(100)  NOT NULL,
    EMAIL              VARCHAR2(254),
    CELL_NO            VARCHAR2(25)   NOT NULL,
    VENUE_ID           VARCHAR2(10)   NOT NULL,
    PARAMEDIC_TEAM_ID  VARCHAR2(20),
    CONSTRAINT UQ_ATTENDEE_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_ATTENDEE_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID),
    CONSTRAINT FK_ATTENDEE_PARAMEDIC
        FOREIGN KEY (PARAMEDIC_TEAM_ID) REFERENCES PARAMEDIC_TEAM (PARAMEDIC_TEAM_ID)
);

CREATE TABLE TICKET (
    TICKET_CODE   VARCHAR2(20)   CONSTRAINT PK_TICKET PRIMARY KEY,
    PRICE         NUMBER(10,2)   NOT NULL,
    PHASE         VARCHAR2(20),
    TICKET_TYPE   VARCHAR2(30)   NOT NULL,
    VENUE_ID      VARCHAR2(10)   NOT NULL,
    ATTENDEE_ID   VARCHAR2(13),
    CONSTRAINT CK_TICKET_PRICE CHECK (PRICE >= 0),
    CONSTRAINT CK_TICKET_TYPE
        CHECK (TICKET_TYPE IN ('GENERAL', 'VIP', 'VVIP')),
    CONSTRAINT FK_TICKET_VENUE
        FOREIGN KEY (VENUE_ID) REFERENCES VENUE (VENUE_ID),
    CONSTRAINT FK_TICKET_ATTENDEE
        FOREIGN KEY (ATTENDEE_ID) REFERENCES ATTENDEE (ATTENDEE_ID)
);

CREATE TABLE STALL_PURCHASE (
    PURCHASE_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT PK_STALL_PURCHASE PRIMARY KEY,
    PURCHASED_ITEM VARCHAR2(100)  NOT NULL,
    QUANTITY       NUMBER(5)      DEFAULT 1 NOT NULL,
    UNIT_PRICE     NUMBER(10,2),
    PURCHASED_AT   TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    STALL_NO       VARCHAR2(50)   NOT NULL,
    ATTENDEE_ID    VARCHAR2(13)   NOT NULL,
    CONSTRAINT CK_PURCHASE_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_PURCHASE_PRICE CHECK (UNIT_PRICE IS NULL OR UNIT_PRICE >= 0),
    CONSTRAINT FK_PURCHASE_STALL
        FOREIGN KEY (STALL_NO) REFERENCES STALL (STALL_NO),
    CONSTRAINT FK_PURCHASE_ATTENDEE
        FOREIGN KEY (ATTENDEE_ID) REFERENCES ATTENDEE (ATTENDEE_ID)
);

/* Index foreign-key columns to support common joins. */
CREATE INDEX IX_PARAMEDIC_VENUE ON PARAMEDIC_TEAM (VENUE_ID);
CREATE INDEX IX_STAGE_VENUE ON STAGE (VENUE_ID);
CREATE INDEX IX_ARTIST_STAGE ON ARTIST (STAGE_NO);
CREATE INDEX IX_SECURITY_VENUE ON SECURITY_TEAM (VENUE_ID);
CREATE INDEX IX_SECURITY_STAGE ON SECURITY_TEAM (STAGE_NO);
CREATE INDEX IX_SECURITY_ARTIST ON SECURITY_TEAM (ARTIST_ID);
CREATE INDEX IX_STALL_VENUE ON STALL (VENUE_ID);
CREATE INDEX IX_ATTENDEE_VENUE ON ATTENDEE (VENUE_ID);
CREATE INDEX IX_ATTENDEE_PARAMEDIC ON ATTENDEE (PARAMEDIC_TEAM_ID);
CREATE INDEX IX_TICKET_VENUE ON TICKET (VENUE_ID);
CREATE INDEX IX_TICKET_ATTENDEE ON TICKET (ATTENDEE_ID);
CREATE INDEX IX_PURCHASE_STALL ON STALL_PURCHASE (STALL_NO);
CREATE INDEX IX_PURCHASE_ATTENDEE ON STALL_PURCHASE (ATTENDEE_ID);
